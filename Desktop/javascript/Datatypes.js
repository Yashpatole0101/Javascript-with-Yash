
console.log("----- DATA TYPES -----");

// 1. String
let name = "Yash";
console.log(name);
console.log(typeof name);

// 2. Number
let age = 21;
console.log(age);
console.log(typeof age);

// 3. Boolean
let isDeveloper = true;
console.log(isDeveloper);
console.log(typeof isDeveloper);

// 4. Undefined
let salary;
console.log(salary);
console.log(typeof salary);

// 5. Null
let address = null;
console.log(address);
console.log(typeof address);

// 6. Array
let skills = ["Java", "JavaScript", "SQL"];
console.log(skills);
console.log(typeof skills);

// 7. Object
let student = {
    name: "Yash",
    age: 21
};
console.log(student);
console.log(typeof student);
